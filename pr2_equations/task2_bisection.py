"""Задание 2б. Метод половинного деления, точность 1e-3.

Отрезок [2,5; 2,6] (см. задание 1). Итерации идут, пока половина
длины отрезка (b - a)/2 больше eps. Ответ — середина последнего отрезка.
"""
from common import F, A, B


def bisection(a, b, eps):
    n = 0
    print(f"{'n':>2} | {'a':>9} | {'b':>9} | {'x=(a+b)/2':>9} | {'F(a)':>9} | {'F(x)':>9} | {'(b-a)/2':>8}")
    while (b - a) / 2 > eps:
        x = (a + b) / 2
        print(f"{n:2d} | {a:9.5f} | {b:9.5f} | {x:9.5f} | {F(a):9.5f} | {F(x):9.5f} | {(b - a) / 2:8.5f}")
        if F(a) * F(x) <= 0:
            b = x
        else:
            a = x
        n += 1
    x = (a + b) / 2
    return x, (b - a) / 2, n


if __name__ == "__main__":
    eps = 1e-3
    x, err, n = bisection(A, B, eps)
    print(f"\nКорень x = {x:.6f} ± {err:.6f}, шагов деления: {n}")
    print(f"С точностью 1e-3: x = {x:.3f}")
