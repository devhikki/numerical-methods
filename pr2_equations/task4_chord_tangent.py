"""Задание 4. Комбинированный метод хорд и касательных, точность 1e-6.

На [2,5; 2,6]: F(2,5) > 0, F(2,6) < 0, F''(x) = -sin x < 0.
Конец c, где F(c)*F''(c) > 0, — это c = 2,6: с него идёт метод касательных,
он же неподвижный конец хорды. От другого конца (2,5) идёт метод хорд.

Касательные: x_{n+1} = x_n - F(x_n)/F'(x_n)
Хорды (2.22): x_{n+1} = (c*F(x_n) - x_n*F(c)) / (F(x_n) - F(c))
Ответ (2.23): середина между приближениями; погрешность (2.24) — половина разности.
"""
from common import F, dF, d2F, A, B


def combined(a, b, eps):
    if F(a) * d2F(a) > 0:
        c = a
        xt, xc = a, b
    else:
        c = b
        xt, xc = b, a
    print(f"c = {c} (F(c)*F''(c) > 0): касательные от {xt}, хорды от {xc}")
    n = 0
    print(f"{'n':>2} | {'хорды':>12} | {'касательные':>12} | {'полуразность':>12}")
    while True:
        xt = xt - F(xt) / dF(xt)
        xc = (c * F(xc) - xc * F(c)) / (F(xc) - F(c))
        n += 1
        half = abs(xt - xc) / 2
        print(f"{n:2d} | {xc:12.8f} | {xt:12.8f} | {half:12.3e}")
        if half <= eps:
            return (xt + xc) / 2, half, n


if __name__ == "__main__":
    x, err, n = combined(A, B, 1e-6)
    print(f"\nКорень x = {x:.6f} ± {err:.1e} (итераций: {n}), F(x) = {F(x):.2e}")
